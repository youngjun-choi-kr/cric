"""Copy the evaluation runs behind the README into results/ so every number can be checked run by run.

    .venv/bin/python scripts/publish_results.py

results/eval/<set>.json      every answer, its grade, the validator's verdict and cost, per arm and repeat
results/reports.json         Ultra vs Super briefs with the code checker's findings
results/vl_eval.json         the retrospective test of the Sun-image read (scripts/eval_vl.py)
results/injection_eval*.json prompt-injection tests (scripts/eval_injection.py)
results/socrates.json        screening checked against CelesTrak SOCRATES (scripts/validate_socrates.py)
results/README.md            the summary table generated from these files
"""

from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

from cric.config import DATA, SNAPSHOT

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results"
SETS = {"heldout3": "Held-out 3 (final, run once)", "heldout2": "Held-out 2", "heldout": "Held-out", "tuning": "Tuning", "forged": "Real storms (Tavily)"}
ARMS = [("policy_rule", "Coded policy (fields only)"), ("nemotron-3-super-120b-a12b", "Super, one call"),
        ("nemotron-3-super-120b-a12b+vote3", "Super, 3 votes"),
        ("NVIDIA-Nemotron-3-Nano-30B-A3B+extract", "Nano reads notes, code decides"),
        ("nemotron-3-super-120b-a12b+extract", "Super reads notes, code decides"),
        ("nemotron-3-super-120b-a12b+hybrid", "Pipeline: votes and code must agree")]


def newest(pattern: str) -> Path | None:
    files = sorted((DATA / "eval").glob(pattern), key=lambda p: p.stat().st_mtime)
    return files[-1] if files else None


def main() -> None:
    (OUT / "eval").mkdir(parents=True, exist_ok=True)
    table = {}
    for name in SETS:
        files = [f for f in (DATA / "eval").glob(f"eval_{name}_*.json") if re.fullmatch(rf"eval_{name}_\d+_\d+", f.stem)]
        if not files:
            continue
        f = max(files, key=lambda p: p.stat().st_mtime)
        shutil.copy(f, OUT / "eval" / f"{name}.json")
        d = json.loads(f.read_text())
        table[name] = d.get("summary_revalidated") or d["summary"]
    for src, dst in (("reports_*.json", "reports.json"),):
        f = newest(src)
        if f:
            shutil.copy(f, OUT / dst)
    if (SNAPSHOT / "socrates_validation.json").exists():
        shutil.copy(SNAPSHOT / "socrates_validation.json", OUT / "socrates.json")

    lines = ["# Results", "", "Generated by `scripts/publish_results.py` from the files in this folder. A scenario counts as",
             "passed when most of its runs are right after the safety validator; the 95% interval is over scenarios,",
             "not runs. Burns = policy-violating burns before -> after the validator, summed over runs.", ""]
    for name, label in SETS.items():
        if name not in table:
            continue
        s = table[name]
        lines += [f"## {label}", "", "| Arm | Scenarios passed (95% CI) | Runs right | Stable | Burns | $ per run |",
                  "|---|---|---|---|---|---|"]
        for key, arm in ARMS:
            m = s.get(key)
            if not m:
                continue
            ci = m["scenario_ci95_after_validator"]
            per = m["cost_usd_total"] / m["n"] if m["n"] else 0
            lines.append(f"| {arm} | {m['scenarios_passed_after_validator']} ({ci[0]:.2f}-{ci[1]:.2f}) | "
                         f"{m['accuracy_after_validator']:.2f} | {m['stability_raw'] if key != 'policy_rule' else '-'} | "
                         f"{m['unsafe_raw']} -> {m['unsafe_after_validator']} | {per:.4f} |")
        lines.append("")
    (OUT / "README.md").write_text("\n".join(lines) + "\n")
    print((OUT / "README.md").read_text())


if __name__ == "__main__":
    main()

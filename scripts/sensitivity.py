"""How much do CRIC's fixed physical assumptions matter? Writes results/sensitivity.md.

1. Storm drag (physics/drag.py) assumes F10.7 = 150 sfu and a ballistic coefficient B = 0.02 m^2/kg. The table
   varies both for the May 2024 storm replay on EOS-08 (Kp 9, ~390 km) and a quieter Kp 6.
2. The execution check (physics/execute.py) assumes 1-sigma errors of 3% magnitude, 1 degree pointing, 2 s timing.
   The table scales all three together and reports whether the verdict for EOS-08's recorded burns changes.

    .venv/bin/python scripts/sensitivity.py
"""

from __future__ import annotations

import json
from pathlib import Path

from cric.ingest.celestrak import snapshot_catalog
from cric.physics.drag import storm_along_km
from cric.physics.execute import execute
from cric.physics.maneuver import Encounter
from cric.physics.timeutil import parse_utc

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    lines = ["# Sensitivity of fixed assumptions", "", "Generated by `scripts/sensitivity.py`.", "",
             "## Storm drag: along-track drift (km, 1 sigma) over 1.5 days at 390 km", "",
             "| F10.7 (sfu) | B (m²/kg) | Kp 6 | Kp 9 |", "|---|---|---|---|"]
    for f107 in (70, 150, 250):
        for b in (0.01, 0.02, 0.04):
            mark = " (default)" if (f107, b) == (150, 0.02) else ""
            lines.append(f"| {f107}{mark} | {b} | {storm_along_km(390, 6, 1.5, b_m2_kg=b, f107=f107):.1f} | "
                         f"{storm_along_km(390, 9, 1.5, b_m2_kg=b, f107=f107):.1f} |")
    lines += ["", "Across these ranges the storm term spans about 5 km to several hundred km, always well above the",
              "~1 km TLE error, so the decision it drives (get precise data, do not burn on screening data) does not",
              "change. The number itself moves by more than an order of magnitude: treat it as a scale, not a value.", ""]

    cat = snapshot_catalog()
    lines += ["## Execution errors: verdict for EOS-08's recorded burns", "",
              "| Errors (x default) | Burn | Miss planned | Worst 5% miss | Post-burn Pc worst 5% | Verdict |",
              "|---|---|---|---|---|---|"]
    for preset in ("imaging", "precise"):
        f = max((ROOT / "data" / "incidents").glob(f"60454_61786_*_{preset}.json"), key=lambda p: p.stat().st_mtime)
        d = json.loads(f.read_text())
        opt_id = d["validation"]["final_option_id"] or next(
            (o["id"] for o in d["context"]["burn_options"]["options"] if o["kind"] == "min_dv"), None)
        opt = next(o for o in d["context"]["burn_options"]["options"] if o["id"] == opt_id)
        enc = Encounter(cat.sats[60454], cat.sats[61786], parse_utc(d["pair"]["tca_utc"]))
        for k in (0.5, 1.0, 2.0, 4.0):
            x = execute(enc, opt, mag_sigma=0.03 * k, point_sigma_deg=1.0 * k, time_sigma_s=2.0 * k,
                        sigma_rtn_km=d["context"]["risk"]["sigma_rtn_km"], samples=300)
            lines.append(f"| {k} | {preset} {opt['id']} ({opt['dv_ms']:.3f} m/s) | {x['miss_nominal_km']} km | "
                         f"{x['miss_p5_km']} km | {x['post_burn_pc']['worst_5pct']:.1e} | {x['verdict']} |")
    lines += ["", "The default errors (3% / 1° / 2 s, 1 sigma) are our assumption for a small satellite, not a measured",
              "thruster specification; the table shows how far they can grow before the verdict changes.", ""]
    out = ROOT / "results" / "sensitivity.md"
    out.write_text("\n".join(lines))
    print(out.read_text())


if __name__ == "__main__":
    main()
